"""Runtime support for scheduled jobs and KV store access.

This module is the Splunk-facing half of the template. It exists so that app code can be
ordinary Python: a scheduled job is a decorated function that returns records, and a KV store
collection is a Pydantic model. Everything Splunk requires to make those two things work -
the modular input protocol, `inputs.conf` plumbing, `collections.conf` field types, the
`sys.path` shim - is either handled here or generated by the build.

Deliberately a single file. If it outgrows that, it should become a separately versioned
library rather than quietly sprawling into a package.

Not modified by app authors. Import from it:

    from splunkapp import scheduled, collection

Runs under Python 3.9 (see `targetPythonVersion` in package.json).
"""

import json
import os
import re
import sys
from dataclasses import dataclass, field
from typing import Any, Callable, Dict, Iterable, List, Optional, Tuple, Union
from xml.sax.saxutils import escape as xml_escape

# Splunk puts the app's `bin/` on sys.path and nothing else - `lib/` is never on it and
# PYTHONPATH is unset. Without this, every bundled third-party import fails. It has to run
# before any of them, which is why it sits at module scope rather than inside a function.
_APP_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
_LIB_DIR = os.path.join(_APP_ROOT, "lib")
if _LIB_DIR not in sys.path:
    sys.path.insert(0, _LIB_DIR)


# --------------------------------------------------------------------------------------
# Scheduled jobs
# --------------------------------------------------------------------------------------

# 5-field cron, minute granularity. Splunk accepts no month/day names, and rejects anything
# it cannot parse - by dropping the input with only a splunkd.log ERROR, while the REST API
# still reports it as enabled. A silent no-run is the worst possible failure mode, so this is
# validated at decoration time (which is also build time, since the build imports job modules
# to generate inputs.conf).
_CRON_FIELD = r"(\*|\d+)(-\d+)?(/\d+)?"
# No whitespace around commas - a field is one token, so that splitting on whitespace below
# lines the fields up with _CRON_RANGES.
_CRON_RE = re.compile(r"^\s*%s(,%s)*(\s+%s(,%s)*){4}\s*$" % ((_CRON_FIELD,) * 4))

_CRON_RANGES = ((0, 59), (0, 23), (1, 31), (1, 12), (0, 7))


@dataclass
class Job:
    """A registered scheduled job. One of these becomes one `inputs.conf` stanza."""

    name: str
    function: Callable
    seconds: Optional[float] = None
    cron: Optional[str] = None
    index: Optional[str] = None
    sourcetype: Optional[str] = None
    description: str = ""

    @property
    def interval(self) -> str:
        """The `inputs.conf` interval value. Splunk accepts seconds or cron in one field."""
        return self.cron if self.cron is not None else str(self.seconds)


_JOBS = {}  # type: Dict[str, Job]


def _validate_cron(expression: str) -> None:
    if not _CRON_RE.match(expression):
        raise ValueError(
            "cron=%r is not a 5-field cron expression. Splunk accepts minute-granularity "
            "cron only, with no month or day names (e.g. '*/5 * * * *'). An invalid value is "
            "not an error at load time - Splunk drops the input and logs to splunkd.log while "
            "still reporting it as enabled, so it is checked here instead." % expression
        )

    for value, (low, high) in zip(expression.split(), _CRON_RANGES):
        for part in value.split(","):
            for number in re.findall(r"\d+", part):
                if not low <= int(number) <= high:
                    raise ValueError(
                        "cron=%r is out of range: %s is not within %d-%d for that field."
                        % (expression, number, low, high)
                    )


def scheduled(
    seconds: Optional[float] = None,
    cron: Optional[str] = None,
    index: Optional[str] = None,
    sourcetype: Optional[str] = None,
) -> Callable:
    """Register a function to run on a schedule.

    Pass exactly one of `seconds` or `cron`. They are separate parameters rather than one
    polymorphic `interval` because their first-run behaviour differs and that difference is
    invisible otherwise: a `seconds` job fires as soon as Splunk registers the input, a `cron`
    job waits for its first matching time.

        @scheduled(seconds=300, index="main", sourcetype="widgets:api")
        def collect(splunk, state, log):
            return [{"widget": w} for w in fetch()]

    The function receives:
      splunk - a `splunklib` Service, authenticated as splunk-system-user with admin. Note
               this is NOT the calling user; a modular input has no user context, unlike a
               REST handler's `Depends(current_splunk_user)`.
      state  - a durable dict, for checkpoints (see `JobState`)
      log    - a stdlib Logger writing to $SPLUNK_HOME/var/log/splunk/

    Return either nothing (for a job that only writes to KV store or Splunk itself), an
    iterable of dicts (indexed as-is), or an iterable of `(epoch_seconds, dict)` tuples to set
    each event's timestamp explicitly. Returning an iterator or generator is fine and is
    preferred for large collections - nothing is buffered.

    Set the timestamp explicitly whenever the source has its own notion of event time.
    Sources commonly report milliseconds; Splunk wants seconds, and feeding it milliseconds
    silently dates events tens of thousands of years into the future.
    """
    if (seconds is None) == (cron is None):
        raise ValueError("@scheduled requires exactly one of seconds= or cron=")

    if cron is not None:
        _validate_cron(cron)
    elif seconds != 0 and seconds != -1 and not (isinstance(seconds, (int, float)) and seconds > 0):
        # 0 means "run continuously" and -1 means "once at startup"; both are legitimate.
        raise ValueError(
            "seconds=%r must be a positive number, 0 (run continuously), or -1 (once at "
            "startup)." % seconds
        )

    def register(function: Callable) -> Callable:
        name = function.__name__
        if name in _JOBS:
            raise ValueError(
                "a scheduled job named %r is already registered. Job names become "
                "inputs.conf stanza names and must be unique across the app." % name
            )
        _JOBS[name] = Job(
            name=name,
            function=function,
            seconds=seconds,
            cron=cron,
            index=index,
            sourcetype=sourcetype,
            description=(function.__doc__ or "").strip().split("\n")[0],
        )
        return function

    return register


