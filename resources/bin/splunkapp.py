@dataclass
class InputConfig:
    """The configuration splunkd sends on stdin for a single stanza."""

    session_key: str
    server_uri: str
    checkpoint_dir: str
    stanza: str
    app: str
    params: Dict[str, str] = field(default_factory=dict)

    @property
    def job_name(self) -> str:
        """`myscheme://collect` -> `collect`."""
        return self.stanza.split("://", 1)[-1]


def _read_input_config(stream: Any) -> InputConfig:
    """Parse splunkd's stdin payload.

    Never log this, and never write it anywhere under var/log/splunk: it carries a live
    session key, that directory is monitored without any extension filter, and the key would
    be indexed into _internal in cleartext.
    """
    from xml.etree import ElementTree

    root = ElementTree.parse(stream).getroot()
    stanza = root.find("./configuration/stanza")
    if stanza is None:
        raise RuntimeError("no <stanza> in the modular input configuration")

    return InputConfig(
        session_key=(root.findtext("session_key") or "").strip(),
        server_uri=(root.findtext("server_uri") or "https://127.0.0.1:8089").strip(),
        checkpoint_dir=(root.findtext("checkpoint_dir") or "").strip(),
        stanza=stanza.get("name") or "",
        app=stanza.get("app") or "",
        params={
            param.get("name"): (param.text or "")
            for param in stanza.findall("param")
            if param.get("name")
        },
    )


def _connect(config: InputConfig) -> Any:
    from splunklib import client

    match = re.match(r"(https?)://([^:/]+):(\d+)", config.server_uri)
    scheme, host, port = match.groups() if match else ("https", "127.0.0.1", "8089")
    return client.connect(
        scheme=scheme, host=host, port=int(port), token="Splunk %s" % config.session_key,
        app=config.app, owner="nobody",
    )


def _emit(records: Iterable[Any], job: Job, stanza: str, stream: Any) -> int:
    """Write records to stdout in Splunk's XML streaming format.

    Streaming rather than simple mode because only this form lets an event carry its own
    timestamp and metadata; simple mode can only infer a timestamp by parsing the text.
    """
    stream.write("<stream>\n")
    count = 0
    for record in records:
        if isinstance(record, tuple):
            timestamp, payload = record  # type: Tuple[float, Dict[str, Any]]
        else:
            timestamp, payload = None, record

        # Quotes need escaping in an attribute value but not in element text, which is why
        # <data> below can take escape()'s defaults and this cannot.
        stream.write('  <event stanza="%s">\n' % xml_escape(stanza, {'"': "&quot;"}))
        if timestamp is not None:
            stream.write("    <time>%r</time>\n" % float(timestamp))
        if job.index:
            stream.write("    <index>%s</index>\n" % xml_escape(job.index))
        if job.sourcetype:
            stream.write("    <sourcetype>%s</sourcetype>\n" % xml_escape(job.sourcetype))
        stream.write("    <data>%s</data>\n" % xml_escape(json.dumps(payload, default=str)))
        stream.write("  </event>\n")
        count += 1
        # Flushing per event keeps a long-running collection visible in Splunk as it goes,
        # rather than appearing all at once when the process exits.
        stream.flush()
    stream.write("</stream>\n")
    stream.flush()
    return count


def _scheme_xml(title: str) -> str:
    return (
        "<scheme>\n"
        "  <title>%s</title>\n"
        "  <description>Scheduled jobs for %s.</description>\n"
        "  <use_external_validation>false</use_external_validation>\n"
        # One process per stanza. Single-instance mode hands every stanza to one process and
        # discards per-stanza index, sourcetype, python.required and scheduling.
        "  <use_single_instance>false</use_single_instance>\n"
        "  <streaming_mode>xml</streaming_mode>\n"
        "  <endpoint><args/></endpoint>\n"
        "</scheme>" % (xml_escape(title), xml_escape(title))
    )


def describe() -> Dict[str, Any]:
    """Everything the build needs to generate conf files, as JSON.

    Invoked at build time with the job modules imported, so the declarations below are exactly
    what the app declared in Python. This is what keeps inputs.conf and collections.conf from
    being a second place to state the same thing.
    """
    return {
        "jobs": [
            {
                "name": job.name,
                "interval": job.interval,
                "index": job.index,
                "sourcetype": job.sourcetype,
                "description": job.description,
            }
            for job in _JOBS.values()
        ],
        "collections": [
            {
                "name": declared.name,
                "fields": declared.fields(),
                "lookup": declared.lookup,
                "undeclarable": declared.undeclarable(),
            }
            for declared in _COLLECTIONS
        ],
    }


def run(title: str = "Scheduled jobs", argv: Optional[List[str]] = None) -> int:
    """Entry point for the generated modular input script.

    The build writes a small `bin/<scheme>.py` that imports this module, imports each job
    module so its `@scheduled` functions register, and calls this.
    """
    argv = sys.argv[1:] if argv is None else argv

    if argv and argv[0] == "--scheme":
        sys.stdout.write(_scheme_xml(title))
        return 0

    if argv and argv[0] == "--validate-arguments":
        return 0

    # Not part of Splunk's protocol - the build calls this to generate conf files.
    if argv and argv[0] == "--describe":
        sys.stdout.write(json.dumps(describe(), indent=2))
        return 0

    config = _read_input_config(sys.stdin)
    job = _JOBS.get(config.job_name)
    log = _make_logger(config.app or "splunkapp", config.job_name)

    if job is None:
        log.error("no @scheduled job named %r is registered for stanza %s",
                  config.job_name, config.stanza)
        return 1

    state = JobState(config.checkpoint_dir, config.job_name)

    try:
        records = job.function(_connect(config), state, log)
        count = _emit(records, job, config.stanza, sys.stdout) if records is not None else 0
        # Only after the job has returned without raising - a failed run should retry its
        # window rather than skip it.
        state.save()
        log.info("completed, %d event(s) emitted", count)
        return 0
    except Exception:
        log.exception("failed")
        return 1
