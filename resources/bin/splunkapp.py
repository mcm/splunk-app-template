# collections.conf supports exactly these four field types. Anything else is a hard App
# Inspect failure.
_SCALAR_TYPES = {
    bool: "bool",
    int: "number",
    float: "number",
    str: "string",
}


def _collection_field_type(annotation: Any) -> Optional[str]:
    """Map a Pydantic annotation to a collections.conf field type, or None to leave it
    undeclared.

    Lists are declared by their element type, not as a container: KV store has no array type,
    but it stores arrays fine and SPL surfaces a list-of-string as a multivalue field. A
    list of objects also round-trips over REST, but SPL silently DROPS it from results, so it
    is left undeclared and warned about rather than pretending it works.
    """
    origin = getattr(annotation, "__origin__", None)
    args = getattr(annotation, "__args__", ())

    # Optional[X] / Union[X, None] - declare by the non-None member.
    if origin is Union:
        members = [a for a in args if a is not type(None)]  # noqa: E721
        return _collection_field_type(members[0]) if len(members) == 1 else None

    if origin in (list, set, tuple):
        return _collection_field_type(args[0]) if args else None

    for python_type, splunk_type in _SCALAR_TYPES.items():
        if annotation is python_type:
            return splunk_type

    # datetime is stored as an epoch value; `time` is what makes SPL treat it as one.
    if getattr(annotation, "__name__", "") == "datetime":
        return "time"

    return None


@dataclass
class Collection:
    """A declared KV store collection. The build turns this into a `collections.conf` stanza.

    Declare it at module scope so the build can find it, then bind it to a Splunk service to
    use it:

        GIZMOS = collection(Gizmo, name="gizmos")

        GIZMOS.bind(splunk).upsert("gizmo-1", Gizmo(...))
    """

    model: Any
    name: str
    lookup: bool = False

    def fields(self) -> Dict[str, str]:
        """Declared field types, derived from the model's annotations."""
        declared = {}
        for field_name, info in self.model.model_fields.items():
            field_type = _collection_field_type(info.annotation)
            if field_type is not None:
                declared[field_name] = field_type
        return declared

    def undeclarable(self) -> List[str]:
        """Fields with no usable collections.conf type. The build warns about these, since a
        list-of-object is invisible to SPL even though it stores and reads back fine."""
        return [
            field_name
            for field_name, info in self.model.model_fields.items()
            if _collection_field_type(info.annotation) is None
        ]

    def bind(self, service: Any, log: Any = None) -> "BoundCollection":
        """Bind this collection to a Splunk service. Pass a job's `log` to hear about waits."""
        return BoundCollection(self, service, log)


_COLLECTIONS = []  # type: List[Collection]


def collection(model: Any, name: Optional[str] = None, lookup: bool = False) -> Collection:
    """Declare a KV store collection backed by a Pydantic model.

    `lookup=True` additionally generates a `transforms.conf` lookup definition, so the
    collection is usable from SPL as `| lookup <name>_lookup ...`. It is opt-in because most
    collections are app state that never needs to appear in a search.
    """
    declared = Collection(model=model, name=name or model.__name__.lower(), lookup=lookup)
    _COLLECTIONS.append(declared)
    return declared


# KV store starts up well after splunkd accepts connections, and until it does every request
# to it fails with 503. This matters because a `seconds=` job fires the moment Splunk registers
# its input - which on a restart is inside that window - so without this a scheduled collector
# reliably fails its first run after every restart.
_KVSTORE_STARTUP_TIMEOUT = 120.0
_KVSTORE_RETRY_INTERVAL = 5.0


def _await_kvstore(operation: Callable, log: Any = None) -> Any:
    """Run a KV store operation, waiting out "KV Store is initializing".

    Only 503 is retried, and only for a bounded time. Every other failure - a missing
    collection, a permission problem, a malformed record - is raised immediately, because
    retrying those just delays the error by two minutes and buries the cause.
    """
    import time as _time

    deadline = _time.time() + _KVSTORE_STARTUP_TIMEOUT
    announced = False
    while True:
        try:
            return operation()
        except Exception as error:
            if getattr(error, "status", None) != 503 or _time.time() >= deadline:
                raise
            if log is not None and not announced:
                log.info("KV store is still starting; waiting up to %ds", _KVSTORE_STARTUP_TIMEOUT)
                announced = True
            _time.sleep(_KVSTORE_RETRY_INTERVAL)


class BoundCollection:
    """CRUD against one collection, as one Splunk user.

    Deliberately thin. Filters are passed through to KV store as-is rather than wrapped in a
    query builder - the query language is Mongo-shaped and already familiar, and hiding it
    would obscure the one part that genuinely is Splunk.
    """

    def __init__(self, declared: Collection, service: Any, log: Any = None):
        self._declared = declared
        self._store = service.kvstore[declared.name].data
        self._log = log

    def get(self, key: str) -> Optional[Any]:
        """Fetch one record by key, or None if it does not exist."""
        try:
            record = _await_kvstore(lambda: self._store.query_by_id(key), self._log)
            return self._declared.model(**record)
        except Exception as error:
            # splunklib raises HTTPError carrying the status; a missing record is not an error
            # worth propagating, but anything else is.
            if getattr(error, "status", None) == 404:
                return None
            raise

    def query(self, filter: Optional[Dict[str, Any]] = None, **options: Any) -> List[Any]:
        """Fetch records matching a KV store filter, e.g. `{"mag": {"$gte": 4.5}}`."""
        query = json.dumps(filter) if filter else None
        records = _await_kvstore(
            lambda: self._store.query(query=query, **options)
            if query
            else self._store.query(**options),
            self._log,
        )
        return [self._declared.model(**record) for record in records]

    def upsert(self, key: str, value: Any) -> str:
        """Insert or replace the record at `key`.

        The key is explicit rather than read off the model because choosing it deliberately is
        what makes writes idempotent. Keying a record on the id of the thing it describes turns
        "acknowledge this item" into a single unconditional write, instead of a query-then-write
        that duplicates records when two people act at once.
        """
        document = value.model_dump(mode="json") if hasattr(value, "model_dump") else dict(value)
        document["_key"] = key
        # KV store has no upsert verb; insert-then-update-on-conflict is the idiom. Only a
        # conflict is retried: catching every exception here turns an unrelated failure - KV
        # store still starting up, a permission problem, a malformed record - into a second,
        # identical failure, and the traceback that reaches the log is then the retry's rather
        # than the one that explains anything.
        try:
            _await_kvstore(lambda: self._store.insert(json.dumps(document)), self._log)
        except Exception as error:
            if getattr(error, "status", None) != 409:
                raise
            _await_kvstore(lambda: self._store.update(key, json.dumps(document)), self._log)
        return key

    def delete(self, key: str) -> None:
        _await_kvstore(lambda: self._store.delete_by_id(key), self._log)


