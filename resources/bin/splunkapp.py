# Checkpoint state
# --------------------------------------------------------------------------------------


class JobState:
    """A durable dict, scoped to one job.

    Splunk provides one checkpoint directory per *scheme*, shared by every job in the app, so
    state is namespaced by job name here. The directory is created by Splunk before the first
    run and survives restarts, which makes it the right home for things like an HTTP
    Last-Modified value used for conditional polling.

    Saved only after the job returns successfully, so a failed run retries the same window
    rather than skipping it.
    """

    def __init__(self, directory: str, job_name: str):
        self._path = os.path.join(directory, "%s.json" % job_name)
        self._values = {}  # type: Dict[str, Any]
        if os.path.exists(self._path):
            try:
                with open(self._path, "r") as handle:
                    self._values = json.load(handle)
            except (ValueError, OSError):
                # A truncated checkpoint should cost one redundant collection, not a crash.
                self._values = {}

    def get(self, key: str, default: Any = None) -> Any:
        return self._values.get(key, default)

    def set(self, key: str, value: Any) -> None:
        self._values[key] = value

    def save(self) -> None:
        # Write-then-rename, so an interrupted write cannot leave an unreadable checkpoint.
        temporary = self._path + ".tmp"
        with open(temporary, "w") as handle:
            json.dump(self._values, handle)
        os.replace(temporary, self._path)


# --------------------------------------------------------------------------------------
# Logging
# --------------------------------------------------------------------------------------


def _make_logger(app: str, job_name: str) -> Any:
    """A logger that cannot corrupt the event stream.

    In a modular input stdout IS the data channel, so anything printed there is indexed as an
    event, and stderr is logged by splunkd at ERROR regardless of what it says. Neither is
    usable for ordinary diagnostics. A file under var/log/splunk is, and Splunk's stock
    monitor indexes it into _internal automatically.

    Never attach a StreamHandler here - logging's default stream is stderr.
    """
    import logging
    import logging.handlers

    logger = logging.getLogger("splunkapp.%s" % job_name)
    if logger.handlers:
        return logger

    logger.setLevel(logging.INFO)
    log_directory = os.path.join(os.environ.get("SPLUNK_HOME", "/opt/splunk"), "var", "log", "splunk")
    handler = logging.handlers.RotatingFileHandler(
        os.path.join(log_directory, "%s.log" % app), maxBytes=5_000_000, backupCount=2
    )
    handler.setFormatter(
        logging.Formatter("%(asctime)s %(levelname)s job=" + job_name + " pid=%(process)d %(message)s")
    )
    logger.addHandler(handler)
    logger.propagate = False
    return logger


