def search(service: Any, spl: str, **options: Any) -> List[Dict[str, Any]]:
    """Run a search and return its results as dicts.

    Intentionally not an abstraction over SPL. Wrapping the job/results-reader dance is worth
    it; hiding the query language is not.
    """
    from splunklib import results as splunk_results  # noqa: F401  (needs the lib/ shim above)

    options.setdefault("output_mode", "json")
    response = service.jobs.oneshot(spl, **options)
    return [row for row in splunk_results.JSONResultsReader(response) if isinstance(row, dict)]


